<x-policy title="Registration and Refund Policy">
    <p>This policy outlines how registration for PROLIS Institute programmes works and how refund requests are handled.</p>

    <h2>Registration</h2>
    <ul>
        <li>Registration is completed by submitting the registration form or contacting our team directly.</li>
        <li>A place on a programme is confirmed once our team has communicated confirmation and any applicable fees have been received.</li>
        <li>Programme places, formats and dates are subject to availability.</li>
    </ul>

    <h2>Fees</h2>
    <p>Course fees and payment details are communicated during registration. Please contact us for information about fees for a specific programme.</p>

    <h2>Refunds</h2>
    <p>Refund requests should be made in writing to our team. Eligibility for a refund depends on when the request is made relative to the programme start date and will be communicated at registration.</p>

    <h2>Programme changes</h2>
    <p>If PROLIS Institute postpones or cancels a programme, registered learners will be offered a place on a later date or an appropriate refund.</p>
</x-policy>
